  final rks = _aesExpandKey(key);
  final out = BytesBuilder(copy: false);
  var prev = iv;
  final usable = data.length - data.length % 16;
  for (var off = 0; off < usable; off += 16) {
    final blk = Uint8List.sublistView(data, off, off + 16);
    final dec = _aesDecryptBlock(rks, blk);
    out.add([for (var i = 0; i < 16; i++) dec[i] ^ prev[i]]);
    prev = blk;
  }
  var bytes = out.takeBytes();
  if (bytes.isNotEmpty && bytes.last >= 1 && bytes.last <= 16) {
    bytes = Uint8List.sublistView(bytes, 0, bytes.length - bytes.last);
  }
  return bytes;
}

Uint8List contentB64Decode(String s) {
  var t = s.trim();
  t += '=' * (-t.length % 4);
  return base64.decode(t);
}

String qimaoDecryptChapterHtml(String content, String key) {
  final trimmedKey = key.trim();
  if (trimmedKey.isEmpty) return content;
  final cd = content + trimmedKey;
  if (cd.length <= 32) return content;
  final token = cd.substring(cd.length - 32);
  final rest = cd.substring(0, cd.length - 32);
  final inner = utf8.decode(contentB64Decode(rest), allowMalformed: true);
  final cipher = contentB64Decode(inner);
  final keyHex = md5.convert(utf8.encode(token)).toString();
  final desKey = Uint8List.fromList(ascii.encode(keyHex.substring(0, 8)));
  var plain = desEcbDecrypt(desKey, cipher);
  if (plain.isNotEmpty && plain.last >= 1 && plain.last <= 8) {
    plain = Uint8List.sublistView(plain, 0, plain.length - plain.last);
  }
  return utf8.decode(plain, allowMalformed: true);
}


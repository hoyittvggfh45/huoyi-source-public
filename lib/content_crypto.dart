int _gmul(int a, int b) {
  var p = 0;
  var x = a;
  var y = b;
  for (var i = 0; i < 8; i++) {
    if (y & 1 != 0) p ^= x;
    final hi = x & 0x80;
    x = (x << 1) & 0xFF;
    if (hi != 0) x ^= 0x1B;
    y >>= 1;
  }
  return p;
}

List<List<int>> _aesExpandKey(Uint8List key) {
  final w = List<int>.from(key);
  for (var i = 4; i < 44; i++) {
    var t = w.sublist(4 * (i - 1), 4 * i);
    if (i % 4 == 0) {
      t = [
        _aesSbox[t[1]] ^ _rcon[i ~/ 4 - 1],
        _aesSbox[t[2]],
        _aesSbox[t[3]],
        _aesSbox[t[0]],
      ];
    }
    for (var j = 0; j < 4; j++) {
      w.add(w[4 * (i - 4) + j] ^ t[j]);
    }
  }
  return [for (var r = 0; r < 11; r++) w.sublist(16 * r, 16 * r + 16)];
}

Uint8List _aesDecryptBlock(List<List<int>> rks, Uint8List block) {
  var s = [for (var i = 0; i < 16; i++) block[i] ^ rks[10][i]];
  for (var rnd = 9; rnd >= 1; rnd--) {
    var t = List<int>.filled(16, 0);
    for (var r = 0; r < 4; r++) {
      for (var c = 0; c < 4; c++) {
        t[r + 4 * c] = _aesInvSbox[s[r + 4 * ((c - r) % 4)]];
      }
    }
    s = [for (var i = 0; i < 16; i++) t[i] ^ rks[rnd][i]];
    t = List<int>.filled(16, 0);
    for (var c = 0; c < 4; c++) {
      final a = s.sublist(4 * c, 4 * c + 4);
      t[4 * c + 0] =
          _gmul(a[0], 14) ^ _gmul(a[1], 11) ^ _gmul(a[2], 13) ^ _gmul(a[3], 9);
      t[4 * c + 1] =
          _gmul(a[0], 9) ^ _gmul(a[1], 14) ^ _gmul(a[2], 11) ^ _gmul(a[3], 13);
      t[4 * c + 2] =
          _gmul(a[0], 13) ^ _gmul(a[1], 9) ^ _gmul(a[2], 14) ^ _gmul(a[3], 11);
      t[4 * c + 3] =
          _gmul(a[0], 11) ^ _gmul(a[1], 13) ^ _gmul(a[2], 9) ^ _gmul(a[3], 14);
    }
    s = t;
  }
  final t = List<int>.filled(16, 0);
  for (var r = 0; r < 4; r++) {
    for (var c = 0; c < 4; c++) {
      t[r + 4 * c] = _aesInvSbox[s[r + 4 * ((c - r) % 4)]];
    }
  }
  return Uint8List.fromList([for (var i = 0; i < 16; i++) t[i] ^ rks[0][i]]);
}


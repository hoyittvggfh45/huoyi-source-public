    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&apos;', "'")
    .replaceAll('&amp;', '&');

List<String> htmlToParagraphs(String htmlText) {
  var t = htmlText;
  t = t.replaceAll(RegExp(r'<br\s*/?>', caseSensitive: false), '\n');

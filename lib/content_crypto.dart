  ];
}

Uint8List? zipEntryBytes(Uint8List zip, String entryName) {
  final bd = ByteData.sublistView(zip);
  var off = 0;
  while (off + 30 <= zip.length &&
      zip[off] == 0x50 &&
      zip[off + 1] == 0x4B &&
      zip[off + 2] == 3 &&
      zip[off + 3] == 4) {
    final method = bd.getUint16(off + 8, Endian.little);
    final compSize = bd.getUint32(off + 18, Endian.little);
    final nameLen = bd.getUint16(off + 26, Endian.little);
    final extraLen = bd.getUint16(off + 28, Endian.little);
    final name = utf8.decode(
      Uint8List.sublistView(zip, off + 30, off + 30 + nameLen),
      allowMalformed: true,
    );
    final dataStart = off + 30 + nameLen + extraLen;
    if (name == entryName) {
      final comp = Uint8List.sublistView(zip, dataStart, dataStart + compSize);
      if (method == 0) return Uint8List.fromList(comp);
      if (method == 8) {
        return Uint8List.fromList(ZLibDecoder(raw: true).convert(comp));
      }
      return null;
    }
    off = dataStart + compSize;
  }
  return null;
}

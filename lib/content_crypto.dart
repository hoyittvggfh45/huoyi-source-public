int _permute(int block, List<int> table, int nbits) {
  var out = 0;
  for (final pos in table) {
    out = (out << 1) | ((block >> (nbits - pos)) & 1);
  }
  return out;
}

List<int> _desSubkeys(Uint8List key8) {
  var k = 0;
  for (final b in key8) {
    k = (k << 8) | b;
  }
  k = _permute(k, _pc1, 64);
  var c = k >> 28;
  var d = k & 0x0FFFFFFF;
  final subs = <int>[];
  for (final s in _shifts) {
    c = ((c << s) | (c >> (28 - s))) & 0x0FFFFFFF;
    d = ((d << s) | (d >> (28 - s))) & 0x0FFFFFFF;
    subs.add(_permute((c << 28) | d, _pc2, 56));
  }
  return subs;
}

int _desF(int r, int sub) {
  final x = _permute(r, _e, 32) ^ sub;
  var out = 0;
  for (var i = 0; i < 8; i++) {
    final six = (x >> (42 - 6 * i)) & 0x3F;
    final row = ((six & 0x20) >> 4) | (six & 0x01);
    final col = (six >> 1) & 0x0F;
    out = (out << 4) | _sbox[i][row * 16 + col];
  }
  return _permute(out, _p, 32);
}

Uint8List desEcbDecrypt(Uint8List key8, Uint8List data) {
  final subs = _desSubkeys(key8);
  final out = BytesBuilder(copy: false);
  final usable = data.length - data.length % 8;
  for (var off = 0; off < usable; off += 8) {
    var block = 0;
    for (var i = 0; i < 8; i++) {
      block = (block << 8) | data[off + i];
    }
    final b = _permute(block, _ip, 64);
    var l = (b >> 32) & 0xFFFFFFFF;
    var r = b & 0xFFFFFFFF;
    for (final sub in subs.reversed) {
      final next = (l ^ _desF(r, sub)) & 0xFFFFFFFF;
      l = r;
      r = next;
    }
    final merged = _permute(
      ((r & 0xFFFFFFFF) << 32) | (l & 0xFFFFFFFF),
      _fp,
      64,
    );
    for (var i = 7; i >= 0; i--) {
      out.addByte((merged >> (8 * i)) & 0xFF);
    }
  }
  return out.takeBytes();
}

